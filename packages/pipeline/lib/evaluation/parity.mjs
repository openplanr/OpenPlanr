import { existsSync, readFileSync, statSync } from 'node:fs';
import { isAbsolute, relative, resolve } from 'node:path';

import { PipelineError } from '../pipeline/errors.mjs';
import { evaluationContentDigest } from '../pipeline/evaluation-identity.mjs';
import {
  buildProfessionalSkillsManifest,
  PROFESSIONAL_SKILLS_CATALOG_PATH,
  PROFESSIONAL_SKILLS_MANIFEST_PATH,
  readProfessionalSkillsCatalog,
  renderProfessionalSkillAssets,
  renderProfessionalSkillsBundle,
} from '../pipeline/professional-skills.mjs';

function fail(code, message, fix = '', details = undefined) {
  throw new PipelineError(code, message, fix, details);
}

/** Digest of the bytes on disk, or null when the declared path is absent. */
function diskDigest(repoRoot, path) {
  const target = resolve(repoRoot, path);
  if (!existsSync(target) || !statSync(target).isFile()) return null;
  return evaluationContentDigest(readFileSync(target));
}

/** True when a packed `files` entry covers a repository-relative path. */
export function packageFilesCover(files, path) {
  return files.some((entry) => (entry.endsWith('/') ? path.startsWith(entry) : entry === path));
}

/** The frozen, package-owned compatibility manifest against its bundled legacy snapshots. */
export function compareGeneratedAssets({ repoRoot }) {
  const catalog = readProfessionalSkillsCatalog({ projectRoot: repoRoot, view: 'legacy' });
  const generated = renderProfessionalSkillsBundle({ projectRoot: repoRoot, view: 'legacy' });
  const mismatches = [];
  let present = 0;
  const declared = [PROFESSIONAL_SKILLS_MANIFEST_PATH];
  for (const path of declared) {
    const expected = evaluationContentDigest(generated[path]);
    const actual = diskDigest(repoRoot, path);
    if (actual === expected) present += 1;
    else mismatches.push(Object.freeze({ path, expected, actual }));
  }
  return Object.freeze({
    declared: declared.length,
    present,
    mismatches: Object.freeze(mismatches),
    catalog,
  });
}

/**
 * Every declared package export subpath resolves to real bytes.
 * A subpath that resolves to nothing is a broken export regardless of the
 * version the package declares.
 */
export function comparePackageExports({ repoRoot, packageJson }) {
  const mismatches = [];
  let declared = 0;
  let present = 0;
  const visit = (value, cursor) => {
    if (typeof value === 'string') {
      if (value.includes('*')) return;
      declared += 1;
      if (diskDigest(repoRoot, value.replace(/^\.\//u, '')) === null)
        mismatches.push(Object.freeze({ subpath: cursor, target: value }));
      else present += 1;
      return;
    }
    if (value && typeof value === 'object' && !Array.isArray(value)) {
      for (const [key, entry] of Object.entries(value))
        visit(entry, key.startsWith('.') ? key : cursor);
    }
  };
  visit(packageJson.exports ?? {}, '.');
  return Object.freeze({ declared, present, mismatches: Object.freeze(mismatches) });
}

/**
 * Package-owned evaluation metadata against what the packed `files` inventory
 * carries. Host prompts are distributed by the root host-package generator and
 * intentionally are not members of the planr-pipeline npm archive.
 */
export function comparePackedMembership({ repoRoot, packageJson, installedRoot = null }) {
  const catalog = readProfessionalSkillsCatalog({ projectRoot: repoRoot, view: 'legacy' });
  const manifest = buildProfessionalSkillsManifest(catalog);
  const files = packageJson.files ?? [];
  const declared = [PROFESSIONAL_SKILLS_CATALOG_PATH, PROFESSIONAL_SKILLS_MANIFEST_PATH].sort();
  const mismatches = [];
  let present = 0;
  for (const path of declared) {
    if (!packageFilesCover(files, path)) {
      mismatches.push(Object.freeze({ path, reason: 'not-covered-by-packed-files' }));
      continue;
    }
    const source = diskDigest(repoRoot, path);
    if (source === null) {
      mismatches.push(Object.freeze({ path, reason: 'absent-from-working-tree' }));
      continue;
    }
    if (installedRoot !== null) {
      const installed = diskDigest(installedRoot, path);
      if (installed !== source) {
        mismatches.push(Object.freeze({ path, reason: 'installed-bytes-diverged' }));
        continue;
      }
    }
    present += 1;
  }
  return Object.freeze({
    declared: declared.length,
    present,
    mismatches: Object.freeze(mismatches),
    manifest,
  });
}

/**
 * Build an isolated compatibility fixture from generated bytes. This exercises
 * host-package membership without reading a sibling checkout during the
 * installed journey; npm package membership is checked separately above.
 */
export function buildDeclaredArchive({ repoRoot, sourceRoot }) {
  const catalog = readProfessionalSkillsCatalog({
    projectRoot: repoRoot,
    view: 'active',
    sourceRoot,
  });
  const generated = renderProfessionalSkillAssets(catalog);
  const archive = {};
  for (const path of Object.keys(generated).sort()) {
    archive[path] = generated[path];
  }
  return Object.freeze(archive);
}

/** Sibling-checkout discovery is a real failure mode, so the installed root is proved self-contained. */
export function assertNoSiblingDiscovery(installedRoot, declaredMembers) {
  for (const path of declaredMembers) {
    const inside = relative(installedRoot, resolve(installedRoot, path));
    if (inside.startsWith('..') || isAbsolute(inside)) {
      fail(
        'E_EVALUATION_PACKED_MEMBER_REFUSED',
        `Declared member ${path} resolves outside the installation root.`,
        'A packed skill is exercised from its own root, never from a sibling checkout.',
        { path },
      );
    }
  }
  return installedRoot;
}
