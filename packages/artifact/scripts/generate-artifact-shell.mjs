import {
  loadArtifactTheme,
  renderArtifactThemeCss,
  renderArtifactThemeJson,
} from '../lib/artifact/ui/tokens.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export const GENERATED_ARTIFACT_THEME_TARGETS = Object.freeze({
  'lib/artifact/ui/generated/artifact-theme.css': 'css',
  'lib/artifact/ui/generated/artifact-theme.json': 'json',
});

/** The sandbox guards as source strings for bridge.mjs; not a hosted shell asset. */
export const ARTIFACT_SANDBOX_GUARDS_PATH = 'lib/artifact/ui/generated/sandbox-guards.mjs';

export const GENERATED_ARTIFACT_SHELL_TARGETS = Object.freeze({
  ...GENERATED_ARTIFACT_THEME_TARGETS,
  [ARTIFACT_SHELL_ASSET_PATHS.template]: 'html',
  [ARTIFACT_SHELL_ASSET_PATHS.manifest]: 'manifest',
  [ARTIFACT_SANDBOX_GUARDS_PATH]: 'module',
  'lib/artifact/ui/diagram-editor.css': 'css',
});

export const ARTIFACT_SHELL_BUNDLE_BANNER =
  '// generated by packages/artifact/scripts/generate-artifact-shell.mjs';

/**
 * Raw and gzip byte ceilings per generated asset, asserted by the package tests.
 * Raise one deliberately, keeping about 20% headroom over the measured size.
 */
export const ARTIFACT_SHELL_ASSET_BUDGETS = Object.freeze({
  'lib/artifact/ui/diagram-editor.css': Object.freeze({ bytes: 98_304, gzipBytes: 20_480 }),
  'lib/artifact/ui/generated/artifact-theme.css': Object.freeze({ bytes: 4_096, gzipBytes: 1_024 }),
  'lib/artifact/ui/generated/artifact-theme.json': Object.freeze({
    bytes: 2_048,
    gzipBytes: 1_024,
  }),
  'templates/artifact-review-shell.html': Object.freeze({ bytes: 68_608, gzipBytes: 13_312 }),
  'templates/artifact-review-stage.js': Object.freeze({ bytes: 450_560, gzipBytes: 96_256 }),
  'templates/design/design-board-adapter.js': Object.freeze({ bytes: 286_720, gzipBytes: 58_368 }),
  'templates/diagram-owner.js': Object.freeze({ bytes: 1_800_000, gzipBytes: 340_000 }),
  'templates/diagram-studio.js': Object.freeze({ bytes: 1_250_000, gzipBytes: 230_000 }),
});

export class ArtifactThemeGenerationError extends Error {
  constructor(code, message, details = {}) {
    super(message);
    this.name = 'ArtifactThemeGenerationError';
    this.code = code;
    this.details = details;
  }
}

export function renderArtifactThemeAssets({ registryPath } = {}) {
  const theme = loadArtifactTheme(registryPath ? { registryPath } : undefined);
  return {
    'lib/artifact/ui/generated/artifact-theme.css': renderArtifactThemeCss(theme),
    'lib/artifact/ui/generated/artifact-theme.json': renderArtifactThemeJson(theme),
  };
}

function sha256(bytes) {
  return createHash('sha256').update(bytes, 'utf8').digest('hex');
}

function assetBudget(path) {
  const budget = ARTIFACT_SHELL_ASSET_BUDGETS[path];
  if (!budget) {
    throw new ArtifactThemeGenerationError(
      'E_ARTIFACT_SHELL_BUDGET_MISSING',
      `Shell asset ${path} has no byte budget in ARTIFACT_SHELL_ASSET_BUDGETS.`,
      { path },
    );
  }
  return budget;
}

export function renderArtifactShellAssetManifest(assets) {
  const records = Object.entries(assets)
    .sort(([left], [right]) => left.localeCompare(right))
    .map(([path, bytes]) => ({
      path,
      bytes: Buffer.byteLength(bytes, 'utf8'),
      sha256: sha256(bytes),
      budget: assetBudget(path),
    }));
  return `${JSON.stringify(
    {
      schemaVersion: '1.1.0',
      name: 'OpenPlanr Artifact Review Shell',
      shellVersion: ARTIFACT_SHELL_VERSION,
      entrypoint: ARTIFACT_SHELL_ASSET_PATHS.template,
      sync: 'byte-for-byte',
      browserApi: {
        stage: '__openPlanrArtifactStage',
        share: '__openPlanrArtifactShare',
        hostedViewer: '__openPlanrHostedArtifactViewer',
        injectedHandlers: [
          'share.prepareShare',
          'share.prepareOwnerCustody',
          'share.saveOwnerCustody',
          'share.createShare',
          'share.copyText',
          'hosted.decodeFragment',
          'hosted.loadShort',
          'hosted.loadRoom',
          'hosted.onEnvelope',
        ],
      },
      assets: records,
    },
    null,
    2,
  )}\n`;
}

/**
 * Bundle one browser entry into a deterministic classic script.
 * Identifiers stay readable and output stays unmapped. The portable stage compacts
 * whitespace and syntax to retain its established byte budget. Third-party
 * license headers stay in place; any esbuild warning fails the build. The empty
 * tsconfig stops a tsconfig.json on disk (its `strict`) from changing the output.
 * `entry` resolves against `projectRoot`; `banner` names the calling generator.
 * `format: 'esm'` leaves an entry that is itself one IIFE unwrapped, keeping its directive.
 */
export function bundleBrowserEntry(
  entry,
  {
    format = 'iife',
    globalName,
    projectRoot = root,
    banner = ARTIFACT_SHELL_BUNDLE_BANNER,
    onInputs,
    compact = false,
  } = {},
) {
  const result = buildSync({
    absWorkingDir: projectRoot,
    entryPoints: [entry],
    banner: { js: banner },
    bundle: true,
    charset: 'utf8',
    format,
    globalName,
    legalComments: 'inline',
    logLevel: 'warning',
    minifyWhitespace: compact,
    minifySyntax: compact,
    minifyIdentifiers: false,
    platform: 'browser',
    define: { 'process.env.NODE_ENV': '"production"' },
    sourcemap: false,
    target: ['es2022'],
    treeShaking: true,
    tsconfigRaw: {},
    write: false,
    metafile: !!onInputs,
  });
  if (result.warnings.length > 0) {
    throw new ArtifactThemeGenerationError(
      'E_ARTIFACT_BUNDLE_WARNINGS',
      `Bundling ${entry} produced ${result.warnings.length} esbuild warning${result.warnings.length === 1 ? '' : 's'}; see the log above.`,
      {
        entry,
        warnings: result.warnings.map(({ id, text, location }) => ({ id, text, location })),
      },
    );
  }
  if (onInputs)
    onInputs(Object.keys(result.metafile.inputs).map((path) => resolve(projectRoot, path)));
  const output = result.outputFiles?.[0]?.text;
  if (typeof output !== 'string' || output.length === 0) {
    throw new ArtifactThemeGenerationError(
      'E_ARTIFACT_BUNDLE_OUTPUT',
      `Bundling ${entry} produced no browser output.`,
      { entry },
    );
  }
  return output.endsWith('\n') ? output : `${output}\n`;
}

