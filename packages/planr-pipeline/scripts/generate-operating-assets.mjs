#!/usr/bin/env node

import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import {
  dirname,
  relative,
  resolve,
  sep,
} from 'node:path';
import { fileURLToPath } from 'node:url';

import { assertProtocolArtifact } from '../lib/protocol/contracts.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export class OperatingAssetGenerationError extends Error {
  constructor(code, message, details = {}) {
    super(message);
    this.name = 'OperatingAssetGenerationError';
    this.code = code;
    this.details = details;
  }
}

function readJson(projectRoot, path) {
  return JSON.parse(readFileSync(resolve(projectRoot, path), 'utf8'));
}

function readCanonicalText(projectRoot, path) {
  return readFileSync(resolve(projectRoot, path), 'utf8').replace(/\r\n?/gu, '\n');
}

function assertUniqueIds(label, records) {
  const ids = records.map(({ id }) => id);
  if (new Set(ids).size !== ids.length) {
    throw new OperatingAssetGenerationError(
      'E_OPERATING_REGISTRY_DUPLICATE_ID',
      `${label} IDs must be unique.`,
    );
  }
}

function markdownCell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function renderAdapterDocs(adapters) {
  const rows = adapters.adapters.map((adapter) => (
    `| ${adapter.id} | ${adapter.version} | ${adapter.capabilityLevel} | ${markdownCell(adapter.entrypoints.artifact)} | ${markdownCell(adapter.entrypoints.operate)} | ${adapter.capabilities.operatingAdvisorDispatch} | ${adapter.capabilities.subagents} | ${adapter.capabilities.toolIsolation} | ${adapter.capabilities.parallelDispatch ? adapter.capabilities.parallelDispatchMode : 'no'} | ${adapter.capabilities.headlessBridge ? 'yes' : 'no'} |`
  ));
  return `<!-- Generated by scripts/generate-operating-assets.mjs. Do not edit. -->\n# Runtime adapters\n\n| Runtime | Adapter | Compatibility | Artifact entrypoint | Operate entrypoint | Advisor dispatch | Subagents | Isolation | Parallel dispatch | Headless bridge |\n|---|---:|---|---|---|---|---|---|---|---|\n${rows.join('\n')}\n`;
}

function renderOperatingRoleDocs(registry) {
  const rows = registry.roles.map((role) => {
    const evidence = role.minimumEvidence.requirements
      .map((entry) => `${entry.source}:${entry.claimTypes.join('+')}≤${entry.maxAgeHours}h`)
      .join(role.minimumEvidence.match === 'all' ? ' + ' : ' or ');
    return `| ${role.order} | ${role.id} | ${role.displayLabel} | ${markdownCell(role.mandate)} | ${role.capabilityTier} | ${role.allowedProposalTypes.join(', ')} | ${role.budgets.maxProposals} | ${markdownCell(evidence)} | ${markdownCell(role.forbiddenRecommendationCategories.join(', '))} | ${role.minimumEvidence.onUnready} |`;
  });
  return `<!-- Generated by scripts/generate-operating-assets.mjs. Do not edit. -->\n# Operating advisor lenses\n\nThese read-only executive lenses are separate from the canonical nine delivery roles. Runtime adapters receive a digest-bound canonical role brief; they must not improvise or widen these instructions.\n\n| Order | ID | Label | Mandate | Capability | Allowed proposals | Max | Minimum evidence | Prohibited recommendations | Unready behavior |\n|---:|---|---|---|---|---|---:|---|---|---|\n${rows.join('\n')}\n`;
}

function renderOperatingProviderDocs(registry) {
  const rows = registry.providers.map((provider) => (
    `| ${provider.id} | ${provider.version} | ${provider.kind} | ${provider.availability} | ${provider.evidenceKinds.join(', ')} | ${provider.limits.maxItems} | ${provider.limits.maxBytes} |`
  ));
  return `<!-- Generated by scripts/generate-operating-assets.mjs. Do not edit. -->\n# Operating evidence providers\n\nAll launch providers are read-only. Runtime adapters may reduce access but cannot widen these limits.\n\n| Provider | Version | Kind | Availability | Evidence | Max items | Max bytes |\n|---|---:|---|---|---|---:|---:|\n${rows.join('\n')}\n`;
}

function operatingLensSummary(registry) {
  return registry.roles
    .map((role) => `${role.displayLabel} (${role.id}: ${role.mandate})`)
    .join('; ');
}

export function renderOperatingAssets({ projectRoot = root } = {}) {
  const packageJson = readJson(projectRoot, 'package.json');
  const adapters = readJson(projectRoot, 'registry/adapters.json');
  const roles = readJson(projectRoot, 'registry/operating-roles.json');
  const providers = readJson(projectRoot, 'registry/operating-providers.json');
  assertProtocolArtifact('adapter-registry', adapters);
  assertProtocolArtifact('operating-role-registry', roles);
  assertProtocolArtifact('operating-provider-registry', providers);
  assertUniqueIds('Adapter', adapters.adapters);
  assertUniqueIds('Operating role', roles.roles);
  assertUniqueIds('Operating provider', providers.providers);
  if (
    adapters.pipelineVersion !== packageJson.version
    || adapters.adapters.some((adapter) => adapter.version !== packageJson.version)
  ) {
    throw new OperatingAssetGenerationError(
      'E_OPERATING_ADAPTER_VERSION_DRIFT',
      `Adapter versions must match pipeline package ${packageJson.version}.`,
    );
  }
  return {
    'adapters/codex/skills/planr-operate/SKILL.md': readCanonicalText(
      projectRoot,
      'templates/runtime/planr-operate-skill.md.tpl',
    ).replace('{{OPERATING_LENSES}}', operatingLensSummary(roles)),
    'adapters/cursor/rules/openplanr-operate.mdc': readCanonicalText(
      projectRoot,
      'templates/runtime/planr-operate-cursor.mdc.tpl',
    ).replace('{{OPERATING_LENSES}}', operatingLensSummary(roles)),
    'commands/operate.md': readCanonicalText(
      projectRoot,
      'templates/runtime/planr-operate-command.md.tpl',
    ).replace('{{OPERATING_LENSES}}', operatingLensSummary(roles)),
    'docs/generated/adapters.md': renderAdapterDocs(adapters),
    'docs/generated/operating-providers.md': renderOperatingProviderDocs(providers),
    'docs/generated/operating-roles.md': renderOperatingRoleDocs(roles),
  };
}

function staleTargets(projectRoot, assets) {
  return Object.entries(assets)
    .filter(([target, expected]) => {
      const path = resolve(projectRoot, target);
      return !existsSync(path) || readFileSync(path, 'utf8') !== expected;
    })
    .map(([target]) => target)
    .sort();
}

function parseArgs(argv) {
  const unsupported = argv.filter((arg) => arg !== '--check');
  if (unsupported.length) {
    throw new OperatingAssetGenerationError(
      'E_OPERATING_ASSET_ARGUMENT',
      `Unsupported argument${unsupported.length === 1 ? '' : 's'}: ${unsupported.join(', ')}`,
    );
  }
  return { check: argv.includes('--check') };
}

export function runOperatingAssetGenerator({
  argv = process.argv.slice(2),
  projectRoot = root,
} = {}) {
  const { check } = parseArgs(argv);
  const assets = renderOperatingAssets({ projectRoot });
  const stale = staleTargets(projectRoot, assets);
  if (check) {
    if (stale.length) {
      throw new OperatingAssetGenerationError(
        'E_OPERATING_ASSET_DRIFT',
        `Generated Operating Board assets are stale:\n${stale.map((target) => `  - ${target}`).join('\n')}\nRun: npm run generate:operating-assets`,
        { staleTargets: stale },
      );
    }
    return { ok: true, mode: 'check', staleTargets: [] };
  }

  const written = [];
  for (const [target, bytes] of Object.entries(assets).sort(([left], [right]) => left.localeCompare(right))) {
    const path = resolve(projectRoot, target);
    mkdirSync(dirname(path), { recursive: true });
    if (!existsSync(path) || readFileSync(path, 'utf8') !== bytes) {
      writeFileSync(path, bytes, 'utf8');
      written.push(relative(projectRoot, path).split(sep).join('/'));
    }
  }
  return { ok: true, mode: 'write', written };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = runOperatingAssetGenerator();
    const changed = result.written?.length ?? 0;
    process.stdout.write(
      result.mode === 'check'
        ? 'Operating Board generated assets are current.\n'
        : `Generated ${changed} Operating Board asset${changed === 1 ? '' : 's'}.\n`,
    );
  } catch (error) {
    process.stderr.write(`${error.code ?? 'E_OPERATING_ASSET_GENERATION'}: ${error.message}\n`);
    process.exitCode = 1;
  }
}
