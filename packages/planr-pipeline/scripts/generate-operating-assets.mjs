#!/usr/bin/env node

import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import {
  dirname,
  relative,
  resolve,
  sep,
} from 'node:path';
import { fileURLToPath } from 'node:url';

import { assertProtocolArtifact } from '../lib/protocol/contracts.mjs';
import { createMissionToolGrant } from '../lib/operate/mission-packet.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const LENS_AGENT_TEMPLATE = 'templates/runtime/operating-lens-agent.md.tpl';
const LENS_AGENT_DOCS = 'docs/generated/operating-lens-agents.md';

/**
 * The nine canonical delivery agents. A generated Operating Board lens agent must
 * never collide with one of these paths. Lens agents are written under
 * `agents/operating/` so a collision is structurally impossible; the guard in
 * `renderOperatingLensAgentAssets` asserts it anyway.
 */
const CANONICAL_DELIVERY_AGENTS = Object.freeze([
  'agents/backend-agent.md',
  'agents/frontend-agent.md',
  'agents/db-agent.md',
  'agents/designer-agent.md',
  'agents/specification-agent.md',
  'agents/qa-agent.md',
  'agents/devops-agent.md',
  'agents/doc-gen-agent.md',
  'agents/entity-scaffold-agent.md',
]);

/**
 * Deterministic bounded read-only grant -> Claude Code `tools:` mapping (FR2/FR4).
 * Every mission-mode lens receives the same closed, read-only grant, so this is
 * the only place a capability ID becomes a Claude tool string. It never emits
 * Edit, Write, or an unscoped `Bash(*)`; a capability outside this table is a
 * hard generation failure rather than a silently dropped grant.
 */
const TOOL_GRANT_TO_CLAUDE_TOOL = Object.freeze({
  'file-read': ['Read'],
  glob: ['Glob'],
  'content-search': ['Grep'],
  'git-log': ['Bash(git log:*)'],
  'git-show': ['Bash(git show:*)'],
  'git-diff': ['Bash(git diff:*)'],
  'git-blame': ['Bash(git blame:*)'],
});

export class OperatingAssetGenerationError extends Error {
  constructor(code, message, details = {}) {
    super(message);
    this.name = 'OperatingAssetGenerationError';
    this.code = code;
    this.details = details;
  }
}

function readJson(projectRoot, path) {
  return JSON.parse(readFileSync(resolve(projectRoot, path), 'utf8'));
}

function readCanonicalText(projectRoot, path) {
  return readFileSync(resolve(projectRoot, path), 'utf8').replace(/\r\n?/gu, '\n');
}

function assertUniqueIds(label, records) {
  const ids = records.map(({ id }) => id);
  if (new Set(ids).size !== ids.length) {
    throw new OperatingAssetGenerationError(
      'E_OPERATING_REGISTRY_DUPLICATE_ID',
      `${label} IDs must be unique.`,
    );
  }
}

function markdownCell(value) {
  return String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function renderAdapterDocs(adapters) {
  const rows = adapters.adapters.map((adapter) => (
    `| ${adapter.id} | ${adapter.version} | ${adapter.capabilityLevel} | ${markdownCell(adapter.entrypoints.artifact)} | ${markdownCell(adapter.entrypoints.operate)} | ${adapter.capabilities.operatingAdvisorDispatch} | ${adapter.capabilities.subagents} | ${adapter.capabilities.toolIsolation} | ${adapter.capabilities.parallelDispatch ? adapter.capabilities.parallelDispatchMode : 'no'} | ${adapter.capabilities.headlessBridge ? 'yes' : 'no'} |`
  ));
  return `<!-- Generated by scripts/generate-operating-assets.mjs. Do not edit. -->\n# Runtime adapters\n\n| Runtime | Adapter | Compatibility | Artifact entrypoint | Operate entrypoint | Advisor dispatch | Subagents | Isolation | Parallel dispatch | Headless bridge |\n|---|---:|---|---|---|---|---|---|---|---|\n${rows.join('\n')}\n`;
}

function renderOperatingRoleDocs(registry) {
  const rows = registry.roles.map((role) => {
    const focus = role.investigationMandate.examine.join('; ');
    return `| ${role.order} | ${role.id} | ${role.displayLabel} | ${markdownCell(role.mandate)} | ${role.capabilityTier} | ${role.allowedProposalTypes.join(', ')} | ${role.budgets.maxProposals} | ${markdownCell(focus)} | ${markdownCell(role.investigationMandate.sufficientGrounding)} | ${markdownCell(role.forbiddenRecommendationCategories.join(', '))} |`;
  });
  return `<!-- Generated by scripts/generate-operating-assets.mjs. Do not edit. -->\n# Operating advisor lenses\n\nThese read-only executive lenses are separate from the canonical nine delivery roles. Each lens is dispatched with an operating mandate — its lens question, investigation focus, declared read boundaries, and citation requirement — and returns a schema-valid cited response the engine resolves into evidence. Runtime adapters must not improvise or widen these instructions.\n\n| Order | ID | Label | Mandate | Capability | Allowed proposals | Max | Investigation focus | Sufficient grounding | Prohibited recommendations |\n|---:|---|---|---|---|---|---:|---|---|---|\n${rows.join('\n')}\n`;
}

function renderOperatingProviderDocs(registry) {
  const rows = registry.providers.map((provider) => (
    `| ${provider.id} | ${provider.version} | ${provider.kind} | ${provider.availability} | ${provider.evidenceKinds.join(', ')} | ${provider.limits.maxItems} | ${provider.limits.maxBytes} |`
  ));
  return `<!-- Generated by scripts/generate-operating-assets.mjs. Do not edit. -->\n# Operating evidence providers\n\nAll launch providers are read-only. Runtime adapters may reduce access but cannot widen these limits.\n\n| Provider | Version | Kind | Availability | Evidence | Max items | Max bytes |\n|---|---:|---|---|---|---:|---:|\n${rows.join('\n')}\n`;
}

function operatingLensSummary(registry) {
  return registry.roles
    .map((role) => `${role.displayLabel} (${role.id}: ${role.mandate})`)
    .join('; ');
}

/**
 * Map the canonical bounded read-only tool grant to a single Claude Code `tools:`
 * string. The grant is fixed policy (the seven bounded read-only tools), so the
 * string is identical for every mandate-dispatched lens and never contains a
 * write, execute, network, or environment capability.
 */
function missionToolsString() {
  const { allowed } = createMissionToolGrant();
  const tools = [];
  for (const capability of allowed) {
    const mapped = TOOL_GRANT_TO_CLAUDE_TOOL[capability];
    if (!mapped) {
      throw new OperatingAssetGenerationError(
        'E_OPERATING_LENS_AGENT_TOOL_UNMAPPED',
        `Read-only grant capability "${capability}" has no Claude Code tool mapping.`,
        { capability },
      );
    }
    for (const tool of mapped) {
      if (!tools.includes(tool)) tools.push(tool);
    }
  }
  return tools.join(', ');
}

/**
 * Project the registry roles into registry order. Every lens is dispatched with
 * an operating mandate (FR1/FR10) — mandate dispatch is the only mode, so no
 * per-role dispatchMode branch survives and every role becomes a native agent.
 */
function lensRolesInOrder(roles) {
  return [...roles.roles].sort((left, right) => left.order - right.order);
}

/**
 * Prove the registry satisfies operating-role-registry@1.3.0 so a generated asset
 * can never drift away from the canonical mandate-vocabulary v1.3 contract.
 */
function assertRoleRegistryV13(roles) {
  assertProtocolArtifact('operating-role-registry', roles, { protocolVersion: '1.3.0' });
}

/**
 * Render one generated runtime agent asset per lens, keyed by its
 * `agents/operating/<role-id>.md` target path. Each asset mirrors the
 * delivery-agent frontmatter shape (name/description/tools/model) and carries
 * only the bounded read-only tool grant that fulfils the mandate.
 */
export function renderOperatingLensAgentAssets(roles, { projectRoot = root } = {}) {
  const derived = lensRolesInOrder(roles);
  assertRoleRegistryV13(roles);
  const template = readCanonicalText(projectRoot, LENS_AGENT_TEMPLATE);
  const tools = missionToolsString();
  const assets = {};
  for (const role of derived) {
    const target = `agents/operating/${role.id}.md`;
    if (CANONICAL_DELIVERY_AGENTS.includes(target)) {
      throw new OperatingAssetGenerationError(
        'E_OPERATING_LENS_AGENT_PATH_COLLISION',
        `Generated lens agent ${target} collides with a canonical delivery agent.`,
        { target },
      );
    }
    assets[target] = template
      .replaceAll('{{ROLE_ID}}', role.id)
      .replaceAll('{{DISPLAY_LABEL}}', role.displayLabel)
      .replaceAll('{{MANDATE}}', role.mandate)
      .replaceAll('{{TOOLS}}', tools);
  }
  return assets;
}

/**
 * Render the human-readable companion doc: one row per lens in registry order,
 * naming the generated agent file and its tool grant.
 */
export function renderOperatingLensAgentDocs(roles) {
  const derived = lensRolesInOrder(roles);
  assertRoleRegistryV13(roles);
  const tools = missionToolsString();
  const rows = derived.map((role) => (
    `| ${role.order} | ${role.id} | ${markdownCell(role.displayLabel)} | agents/operating/${role.id}.md | ${markdownCell(tools)} |`
  ));
  return `<!-- Generated by scripts/generate-operating-assets.mjs. Do not edit. -->\n# Operating lens agents\n\nEach lens is generated from \`registry/operating-roles.json\` as a read-only advisory agent under \`agents/operating/\` and dispatched with an operating mandate. These are not delivery agents and never enter \`registry/roles.json\`.\n\n| Order | ID | Label | Generated agent | Tool grant |\n|---:|---|---|---|---|\n${rows.join('\n')}\n`;
}

/**
 * Render the static Operating Board cadence guidance doc (FR8). This is generated
 * *guidance* — a fixed summary of the `manual`/`weekly`/`monthly` contract and of
 * what "computes without executing" means — not a live per-project cadence
 * dashboard (that is OpenPlanr's `status`/dashboard surface). It reads nothing
 * from disk and derives nothing from mutable per-project state, so it renders
 * identically for every project and stays byte-stable for drift detection.
 */
export function renderOperatingCadenceDocs() {
  return [
    '<!-- Generated by scripts/generate-operating-assets.mjs. Do not edit. -->',
    '# Operating cadence',
    '',
    'Cadence decides *when* a cycle is due, never *what* a run may do. Computing a',
    'due date is a pure calculation over the last run instant and an injected clock:',
    'it reads no project state, calls no provider, and dispatches no advisor. All',
    'surfaced timestamps are UTC.',
    '',
    '| Cadence | Runs | Next due date |',
    '|---|---|---|',
    '| `manual` | Only on explicit request | none (`nextDueAt` is `null`) |',
    '| `weekly` | On request; due date surfaced in `status` | `lastRunAt + 7 days`, or now on the first run |',
    '| `monthly` | On request; due date surfaced in `status` | `lastRunAt + 1 calendar month` (same day-of-month, clamped to a shorter month), or now on the first run |',
    '',
    '## Computes without executing',
    '',
    'Surfacing a `weekly` or `monthly` due date is not a trigger to act. Optional',
    'scheduled execution MAY be enabled through the runtime, but a cadence- or',
    'schedule-triggered run MUST NOT accept findings, apply routes, invoke PLAN, or',
    'invoke SHIP. R1 remains mandatory: nothing auto-chains to PLAN or SHIP. A',
    'scheduled run stops at the same review gate as a manual run.',
    '',
    'The skill or plugin orchestrates the cycle lifecycle invisibly; the `planr',
    'operate` CLI stays the authoritative surface for state, locks, validation, and',
    'the cadence values shown in `status`.',
    '',
  ].join('\n');
}

export function renderOperatingAssets({ projectRoot = root } = {}) {
  const packageJson = readJson(projectRoot, 'package.json');
  const adapters = readJson(projectRoot, 'registry/adapters.json');
  const roles = readJson(projectRoot, 'registry/operating-roles.json');
  const providers = readJson(projectRoot, 'registry/operating-providers.json');
  assertProtocolArtifact('adapter-registry', adapters);
  assertProtocolArtifact('operating-role-registry', roles);
  assertProtocolArtifact('operating-provider-registry', providers);
  assertUniqueIds('Adapter', adapters.adapters);
  assertUniqueIds('Operating role', roles.roles);
  assertUniqueIds('Operating provider', providers.providers);
  if (
    adapters.pipelineVersion !== packageJson.version
    || adapters.adapters.some((adapter) => adapter.version !== packageJson.version)
  ) {
    throw new OperatingAssetGenerationError(
      'E_OPERATING_ADAPTER_VERSION_DRIFT',
      `Adapter versions must match pipeline package ${packageJson.version}.`,
    );
  }
  const assets = {
    'adapters/codex/skills/planr-operate/SKILL.md': readCanonicalText(
      projectRoot,
      'templates/runtime/planr-operate-skill.md.tpl',
    ).replace('{{OPERATING_LENSES}}', operatingLensSummary(roles)),
    'adapters/cursor/rules/openplanr-operate.mdc': readCanonicalText(
      projectRoot,
      'templates/runtime/planr-operate-cursor.mdc.tpl',
    ).replace('{{OPERATING_LENSES}}', operatingLensSummary(roles)),
    'commands/operate.md': readCanonicalText(
      projectRoot,
      'templates/runtime/planr-operate-command.md.tpl',
    ).replace('{{OPERATING_LENSES}}', operatingLensSummary(roles)),
    'docs/generated/adapters.md': renderAdapterDocs(adapters),
    'docs/generated/operating-providers.md': renderOperatingProviderDocs(providers),
    'docs/generated/operating-roles.md': renderOperatingRoleDocs(roles),
    'docs/generated/operating-cadence.md': renderOperatingCadenceDocs(),
  };
  // Fold the generated lens agents + companion doc into the same asset map so
  // staleTargets()/--check cover them automatically. Guarded on the template's
  // presence so a caller that seeds a partial projectRoot (e.g. the CRLF fixture)
  // is not forced to also stage this template; the real repository always ships
  // it, so drift detection is unconditional there.
  if (existsSync(resolve(projectRoot, LENS_AGENT_TEMPLATE))) {
    Object.assign(assets, renderOperatingLensAgentAssets(roles, { projectRoot }));
    assets[LENS_AGENT_DOCS] = renderOperatingLensAgentDocs(roles);
  }
  return assets;
}

function staleTargets(projectRoot, assets) {
  return Object.entries(assets)
    .filter(([target, expected]) => {
      const path = resolve(projectRoot, target);
      return !existsSync(path) || readFileSync(path, 'utf8') !== expected;
    })
    .map(([target]) => target)
    .sort();
}

function parseArgs(argv) {
  const unsupported = argv.filter((arg) => arg !== '--check');
  if (unsupported.length) {
    throw new OperatingAssetGenerationError(
      'E_OPERATING_ASSET_ARGUMENT',
      `Unsupported argument${unsupported.length === 1 ? '' : 's'}: ${unsupported.join(', ')}`,
    );
  }
  return { check: argv.includes('--check') };
}

export function runOperatingAssetGenerator({
  argv = process.argv.slice(2),
  projectRoot = root,
} = {}) {
  const { check } = parseArgs(argv);
  const assets = renderOperatingAssets({ projectRoot });
  const stale = staleTargets(projectRoot, assets);
  if (check) {
    if (stale.length) {
      throw new OperatingAssetGenerationError(
        'E_OPERATING_ASSET_DRIFT',
        `Generated Operating Board assets are stale:\n${stale.map((target) => `  - ${target}`).join('\n')}\nRun: npm run generate:operating-assets`,
        { staleTargets: stale },
      );
    }
    return { ok: true, mode: 'check', staleTargets: [] };
  }

  const written = [];
  for (const [target, bytes] of Object.entries(assets).sort(([left], [right]) => left.localeCompare(right))) {
    const path = resolve(projectRoot, target);
    mkdirSync(dirname(path), { recursive: true });
    if (!existsSync(path) || readFileSync(path, 'utf8') !== bytes) {
      writeFileSync(path, bytes, 'utf8');
      written.push(relative(projectRoot, path).split(sep).join('/'));
    }
  }
  return { ok: true, mode: 'write', written };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const result = runOperatingAssetGenerator();
    const changed = result.written?.length ?? 0;
    process.stdout.write(
      result.mode === 'check'
        ? 'Operating Board generated assets are current.\n'
        : `Generated ${changed} Operating Board asset${changed === 1 ? '' : 's'}.\n`,
    );
  } catch (error) {
    process.stderr.write(`${error.code ?? 'E_OPERATING_ASSET_GENERATION'}: ${error.message}\n`);
    process.exitCode = 1;
  }
}
